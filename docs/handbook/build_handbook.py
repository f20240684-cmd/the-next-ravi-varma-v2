def section(text: str, prefix):
    if prefix is None:
        return text.strip()
    start = text.index(prefix)
    nxt = re.search(r"^## ", text[start + 3:], re.M)
    return text[start: start + 3 + nxt.start() if nxt else len(text)].strip()


def write_extracts() -> None:
    for name, parts in EXTRACTS.items():
        body = "\n\n".join(section((SRC / f).read_text(encoding="utf-8"), pre) for f, pre in parts)
        (HERE / name).write_text(f"<!-- Extracted from the technical handbook (docs/handbook/src/); edit the source "
                                 f"files and rerun build_handbook.py. Commit {COMMIT}. -->\n\n{body}\n",
                                 encoding="utf-8")


def render_html(md: str, page_of: dict) -> str:
    mdi = MarkdownIt("commonmark", {"html": True}).enable("table")

    def fence(self, tokens, idx, options, env):
        tok = tokens[idx]
        lang = tok.info.strip().split()[0] if tok.info.strip() else ""
        if lang == "mermaid":
            return f'<pre class="mermaid">{html.escape(tok.content)}</pre>\n'
        try:
            lexer = get_lexer_by_name(lang) if lang else TextLexer()
        except Exception:
            lexer = TextLexer()
        return highlight(tok.content, lexer, HtmlFormatter(noclasses=True, nowrap=False, style="friendly"))

    mdi.add_render_rule("fence", fence)
    tokens = mdi.parse(md)
    seen, toc = {}, []
    for i, tok in enumerate(tokens):
        if tok.type == "heading_open" and tok.tag in ("h1", "h2"):
            text = tokens[i + 1].content
            hid = slug(text, seen)
            tok.attrSet("id", hid)
            toc.append((tok.tag, text, hid))
    body = mdi.renderer.render(tokens, mdi.options, {})
    # let long paths / dotted names wrap at sensible points instead of overflowing table cells
    body = re.sub(r"<code>(.*?)</code>",
                  lambda m: "<code>" + re.sub(r"([/._])(?=\w)", r"\1<wbr>", m.group(1)) + "</code>", body)

    items = []
    for tag, text, hid in toc:
        label = re.sub(r"`", "", text)
        page = page_of.get(hid, "000")  # placeholder of the same width in pass 1
        items.append(f'<li class="{"l1" if tag == "h1" else "l2"}"><a href="#{hid}">{html.escape(label)}</a>'
                     f'<span class="dots"></span><span>{page}</span></li>')
    cover = (f'<div class="cover"><div class="t">The Next Ravi Varma</div>'
             f'<div class="s">Complete Technical Handbook</div><div class="bar"></div>'
             f'<div class="s">Stable Diffusion 1.5 + LoRA style model of Raja Ravi Varma — data, training, '
             f'generation, evaluation and the web app, explained from first principles</div>'
             f'<div class="m">Repository: f20240684-cmd/the-next-ravi-varma-v2<br>Grounded in commit {COMMIT}'
             f'<br>Generated {time.strftime("%d %B %Y")}<br>Documentation only — no application code was changed'
             f'</div></div>')
    toc_html = f'<div class="toc"><h1 id="contents">Contents</h1><ul>{"".join(items)}</ul></div>'
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>The Next Ravi Varma Handbook</title>
<style>{CSS}</style></head><body>{cover}{toc_html}{body}
<script src="https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"></script>
<script>
mermaid.initialize({{startOnLoad: false, theme: 'neutral', securityLevel: 'strict',
  flowchart: {{useMaxWidth: true, htmlLabels: true}}, sequence: {{useMaxWidth: true, wrap: true, width: 120, actorMargin: 25, messageMargin: 30, noteMargin: 8}}, er: {{useMaxWidth: true}}}});
(async () => {{
  const errs = [];
  for (const [i, el] of [...document.querySelectorAll('pre.mermaid')].entries()) {{
    const src = el.textContent;
    try {{ await mermaid.run({{nodes: [el]}}); }}
    catch (e) {{ errs.push(i + ': ' + (e.message || e.str || JSON.stringify(e)).slice(0, 300) + ' | ' + src.slice(0, 60)); }}
  }}
  window.__mermaidErrors = errs;
  window.__mermaidDone = errs.length ? 'errors' : 'ok';
}})();
</script></body></html>"""


def find_browser() -> str:
    for b in BROWSERS:
        if b and Path(b).exists():
            return b
    raise SystemExit("No Chromium-family browser found; set $CHROME to its executable.")


async def print_pdf(html_path: Path, pdf_path: Path) -> dict:
    import websockets

    port = 9344
    proc = subprocess.Popen([find_browser(), "--headless=new", f"--remote-debugging-port={port}",
                             f"--user-data-dir={tempfile.mkdtemp()}", "--disable-gpu", "--disable-extensions",
                             "about:blank"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        for _ in range(60):
            try:
                targets = json.load(urllib.request.urlopen(f"http://127.0.0.1:{port}/json"))
                break
            except Exception:
                time.sleep(0.3)
        ws_url = next(t["webSocketDebuggerUrl"] for t in targets if t["type"] == "page")
        async with websockets.connect(ws_url, max_size=500_000_000, ping_interval=None) as ws:
            n = 0

            async def cmd(method, **params):
                nonlocal n
                n += 1
                my = n
                await ws.send(json.dumps({"id": my, "method": method, "params": params}))
                while True:
                    msg = json.loads(await ws.recv())
                    if msg.get("id") == my:
                        if "error" in msg:
                            raise RuntimeError(f"{method}: {msg['error']}")
                        return msg.get("result", {})

            async def js(expr):
                r = await cmd("Runtime.evaluate", expression=expr, awaitPromise=True, returnByValue=True)
                return r.get("result", {}).get("value")

            await cmd("Page.enable")
            await cmd("Page.navigate", url=html_path.as_uri())
            status = None
            for _ in range(240):
                status = await js("window.__mermaidDone || null")
                if status:
                    break
                await asyncio.sleep(0.5)
            stats = {
                "mermaid_status": status or "timeout",
                "mermaid_blocks": await js("document.querySelectorAll('pre.mermaid').length"),
                "mermaid_svgs": await js("document.querySelectorAll('pre.mermaid svg').length"),
                "mermaid_errors": await js("document.querySelectorAll('pre.mermaid [aria-roledescription=error], "
                                           "pre.mermaid .error-icon').length"),
                "mermaid_error_messages": await js("window.__mermaidErrors || []"),
                # rendered / natural width per diagram; below ~0.6 the labels get too small to read
                "mermaid_scales": await js(
                    "[...document.querySelectorAll('pre.mermaid svg')].map(s => "
                    "+(s.getBoundingClientRect().width / s.viewBox.baseVal.width).toFixed(2))"),
                "wide_elements": await js(
                    "[...document.querySelectorAll('table, pre, svg')].filter(e => e.scrollWidth > "
                    "document.body.clientWidth + 2).map(e => e.tagName + ': ' + e.textContent.slice(0, 80))"),
            }
            foot = ('<div style="font-size:7.5px;width:100%;padding:0 15mm;color:#888;display:flex;'
                    'justify-content:space-between"><span>The Next Ravi Varma — Technical Handbook</span>'
                    '<span>Page <span class="pageNumber"></span> of <span class="totalPages"></span></span></div>')
            head = ('<div style="font-size:7.5px;width:100%;padding:0 15mm;color:#aaa;text-align:right">'
                    f'commit {COMMIT}</div>')
            r = await cmd("Page.printToPDF", printBackground=True, preferCSSPageSize=True,
                          displayHeaderFooter=True, headerTemplate=head, footerTemplate=foot)
            pdf_path.write_bytes(base64.b64decode(r["data"]))
            return stats
    finally:
        proc.terminate()


def heading_pages(pdf_path: Path, md: str) -> dict:
    """Page number (1-based) on which each h1/h2 first appears, found by searching the PDF text."""
    try:
        import fitz  # PyMuPDF
    except ImportError:
        return {}
    doc = fitz.open(pdf_path)
    texts = [" ".join(p.get_text().split()) for p in doc]
    mdi = MarkdownIt("commonmark").enable("table")
    tokens = mdi.parse(md)
    seen, pages = {}, {}
    # skip the cover and the contents pages (pass-1 contents carry "000" placeholders)
    toc_pages = [p for p, t in enumerate(texts) if t.count("000") >= 3]
    start = max(toc_pages) + 1 if toc_pages else 2
    for i, tok in enumerate(tokens):
        if tok.type == "heading_open" and tok.tag in ("h1", "h2"):
            raw = tokens[i + 1].content
            hid = slug(raw, seen)
            needle = " ".join(re.sub(r"`", "", raw).split())
            for p in range(start, len(texts)):
                body = texts[p].replace(f"commit {COMMIT}", "", 1).strip()
                # chapters (h1) always start a new page, so match them only at the top of a page
                if (body.startswith(needle) if tok.tag == "h1" else needle in texts[p]):
                    pages[hid] = str(p + 1)
                    start = p
                    break
    return pages


def main():
    md = build_markdown()
    write_extracts()
    OUT_HTML.parent.mkdir(exist_ok=True)
    OUT_HTML.write_text(render_html(md, {}), encoding="utf-8")
    stats = asyncio.run(print_pdf(OUT_HTML, OUT_PDF))
    pages = heading_pages(OUT_PDF, md)
    if pages:  # second pass with real page numbers in the contents
        OUT_HTML.write_text(render_html(md, pages), encoding="utf-8")
        stats = asyncio.run(print_pdf(OUT_HTML, OUT_PDF))
    stats["toc_entries_with_pages"] = len(pages)
    stats["pdf"] = str(OUT_PDF.relative_to(HERE.parent.parent))
    print(json.dumps(stats, indent=2))


if __name__ == "__main__":
    main()
