def slug(text: str, seen: dict) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "section"
    seen[s] = seen.get(s, 0) + 1
    return s if seen[s] == 1 else f"{s}-{seen[s]}"


def build_markdown() -> str:
    parts = [p.read_text(encoding="utf-8").strip() for p in sorted(SRC.glob("*.md"))]
    header = (f"<!-- Generated by docs/handbook/build_handbook.py from docs/handbook/src/*.md "
              f"(repository commit {COMMIT}). Edit the src files, not this one. -->\n\n")
    md = header + "\n\n".join(parts) + "\n"
    OUT_MD.write_text(md, encoding="utf-8")
    return md


